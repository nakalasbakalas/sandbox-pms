/* global console */
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const roomsSource = (await readFile('src/components/rooms/RoomsView.tsx', 'utf8')).replaceAll('\r\n', '\n')
const appSource = (await readFile('src/App.tsx', 'utf8')).replaceAll('\r\n', '\n')
const sidebarSource = (await readFile('src/components/navigation/AppSidebar.tsx', 'utf8')).replaceAll('\r\n', '\n')
const rbacSource = (await readFile('server/rbac.mjs', 'utf8')).replaceAll('\r\n', '\n')

const serverStart = roomsSource.indexOf('function ServerRoomsView()')
const demoStart = roomsSource.indexOf('function DemoRoomsView()')
assert.ok(serverStart >= 0 && demoStart > serverStart, 'Rooms keeps distinct server and demo components')
const serverSlice = roomsSource.slice(serverStart, demoStart)
const demoSlice = roomsSource.slice(demoStart)
const projectionStart = roomsSource.indexOf('function serverRoomsToCards(')
const demoProjectionStart = roomsSource.indexOf('function demoRoomToCard(')
assert.ok(projectionStart >= 0 && demoProjectionStart > projectionStart, 'Rooms keeps a dedicated server room projection')
const serverProjection = roomsSource.slice(projectionStart, demoProjectionStart)

assert.match(roomsSource, /SERVER_API_ENABLED/, 'Rooms explicitly distinguishes server mode from the demo-only browser-data path')
assert.match(roomsSource, /server-rooms-view/, 'the successful server Rooms surface has a stable authority test id')
assert.match(roomsSource, /server-rooms-error/, 'the failed server Rooms surface has a stable authority test id')
assert.match(roomsSource, /Rooms unavailable/, 'Rooms fails closed with a truthful authoritative-data error')
assert.match(roomsSource, /Retry/, 'Rooms exposes a visible retry after an authoritative fetch failure')
assert.match(serverSlice, /useServerBookingBoard\(serverToday\(\), 7\)/, 'server Rooms consumes only the authenticated Board snapshot')
assert.doesNotMatch(serverSlice, /\buseKV\b|\buseRoomSync\b|localStorage|sessionStorage/, 'server Rooms cannot read browser-owned operational state')
assert.match(demoSlice, /useRoomSync\(\)/, 'the legacy room synchronization hook remains confined to demo mode')
assert.match(demoSlice, /useKV<PropertySetup>\('onboarding-property'/, 'browser-owned property data remains confined to demo mode')
assert.match(roomsSource, /reservation\.status === 'CHECKED_IN'/, 'server Rooms only projects checked-in stays')
assert.match(roomsSource, /reservation\.checkIn <= today/, 'server Rooms excludes future arrivals')
assert.match(roomsSource, /reservation\.checkOut > today/, 'server Rooms excludes checked-out stays')
assert.doesNotMatch(serverProjection, /TWIN|DOUBLE/, 'server Rooms never collapses configured room types into legacy buckets')
assert.match(serverProjection, /roomTypeId: room\.roomType\.id/, 'server Rooms retains the authoritative room-type identifier')
assert.match(serverProjection, /roomTypeCode: room\.roomType\.code/, 'server Rooms retains the authoritative room-type code')
assert.match(serverProjection, /roomTypeName: room\.roomType\.name/, 'server Rooms retains the authoritative room-type name')
assert.match(serverProjection, /room\.currentStatus === 'INSPECTED'/, 'server Rooms handles inspected state explicitly')
assert.match(serverProjection, /room\.currentStatus === 'VACANT_CLEAN' \|\| room\.currentStatus === 'INSPECTED'/, 'clean and inspected vacant rooms are both ready')
assert.match(serverSlice, /hasPermission\('view:cashier'\)/, 'balance visibility requires explicit cashier permission')
assert.match(roomsSource, /showBalance && room\.balanceDue !== undefined/, 'zero balances remain truthful while absent balances stay hidden')
assert.doesNotMatch(serverSlice, /guest\.(email|phone|notes|id)|reservation\.(email|phone|notes)/, 'server Rooms does not project guest contact or note fields')
assert.match(serverSlice, /data\.propertyDisplay\.name/, 'Rooms displays the property only from the server snapshot')
assert.match(appSource, /rooms: \['view:board'\]/, 'the client route requires Board permission')
assert.match(sidebarSource, /\{ id: 'rooms'.*permission: 'view:board'/, 'the Rooms navigation item requires Board permission')
assert.match(rbacSource, /rooms: \['view:board'\]/, 'the server route registry requires Board permission')

console.log('Rooms server-authority source guards passed.')
